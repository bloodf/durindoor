#!/usr/bin/env node
// One-shot DDL translator: reads the source SQLite migrations and emits
// the parallel PG migration set under `src/lib/db/migrations/postgres/`.
//
// Usage:
//   node scripts/migrate-sqlite-ddl-to-pg.mjs            # writes files
//   node scripts/migrate-sqlite-ddl-to-pg.mjs --check    # exits 0 if files match
//
// The generator is run once at authoring time; the output is committed
// and `npm run check:postgres-migrations` (`scripts/check-postgres-migrations.mjs`)
// asserts the files are still in sync. This is the same discipline
// `scripts/check-registry-index.mjs` enforces on the registry.

import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(__dirname, "..");
const SQLITE_MIG_DIR = path.join(REPO, "src/lib/db/migrations");
const PG_MIG_DIR = path.join(REPO, "src/lib/db/migrations/postgres");

// Migrations that are TRUE no-ops on PG (the schema is already complete
// from the bootstrap + 017-connection-groups creates partial unique indexes
// for usageHistory.usageEventId).
const NO_OP_MIGRATIONS = new Set([
  "002-mcp-gateway.js",
  "003-mcp-grant-tools.js",
  "004-daily-token-limit.js",
  "005-api-key-expiry.js",
  "006-api-key-policy.js",
  "007-provider-quota-snapshots.js",
  "008-quota-reservations.js",
  "010-token-saver-events.js",
  "011-model-capability-overrides.js",
  "012-mcp-provider-connection.js",
  "013-combo-invariant.js",
  "014-api-key-provider-connections.js",
  "015-combo-members.js",
  "016-combo-capabilities.js",
]);

function listSqliteMigrations() {
  return readdirSync(SQLITE_MIG_DIR)
    .filter((f) => /^\d{3}-.+\.js$/.test(f))
    .sort();
}

function renderBootstrap() {
  return `// AUTO-GENERATED by scripts/migrate-sqlite-ddl-to-pg.mjs — do not edit.
// This file is the PG migration set's helper; it is not a versioned
// migration. The runner calls bootstrapPgMetaTable() before iterating
// PG_MIGRATIONS so the _meta table exists for schemaVersion stamping.

import { translateColumnDef } from "../../dialects/postgres/translate.js";

export function bootstrapPgMetaTable(adapter) {
  adapter.exec(
    \`CREATE TABLE IF NOT EXISTS _meta (
      key TEXT PRIMARY KEY,
      value TEXT NOT NULL
    )\`
  );
}

export function pgMetaSet(adapter, key, value) {
  adapter.run(
    \`INSERT INTO _meta(key, value) VALUES($1, $2)
     ON CONFLICT(key) DO UPDATE SET value = EXCLUDED.value\`,
    [key, String(value)]
  );
}

export function pgMetaGet(adapter, key, fallback) {
  const row = adapter.get(\`SELECT value FROM _meta WHERE key = $1\`, [key]);
  if (!row) return fallback;
  return row.value;
}
`;
}

function renderInitial() {
  return `// AUTO-GENERATED by scripts/migrate-sqlite-ddl-to-pg.mjs — do not edit.
// Equivalent of the SQLite 001-initial.js in PG dialect. The bootstrap
// creates every table declared in \`src/lib/db/schema.js\` using the PG DDL
// translator.

import { TABLES } from "../../schema.js";
import { translateCreateTable } from "../../dialects/postgres/translate.js";

const migration = {
  version: 1,
  name: "initial",
  up(adapter) {
    adapter.exec(
      \`CREATE TABLE IF NOT EXISTS _meta (key TEXT PRIMARY KEY, value TEXT NOT NULL)\`
    );
    for (const [name, def] of Object.entries(TABLES)) {
      const { createSql, indexSqls } = translateCreateTable(name, def);
      adapter.exec(createSql);
      for (const idx of indexSqls) adapter.exec(idx);
    }
  },
};

export default migration;
`;
}

function renderNoOp(file, num, name) {
  return `// AUTO-GENERATED by scripts/migrate-sqlite-ddl-to-pg.mjs — do not edit.
// Mirrors the SQLite ${file}. On PG the bootstrap (#001) already created the
// schema, so this migration is a version-stamp no-op. The runner stamps
// \`schemaVersion = ${num}\` after calling \`up()\`.

const migration = {
  version: ${num},
  name: ${JSON.stringify(name)},
  up(adapter) {
    // No-op on PG.
  },
};

export default migration;
`;
}

function renderConnectionGroups() {
  return `// AUTO-GENERATED by scripts/migrate-sqlite-ddl-to-pg.mjs — do not edit.
// Mirrors the SQLite 017-connection-groups.js. Adds the partial unique
// index on usageHistory.usageEventId that is not part of the declarative
// schema (it depends on the column already existing).

const migration = {
  version: 17,
  name: "connection-groups",
  up(adapter) {
    adapter.exec(
      \`CREATE UNIQUE INDEX IF NOT EXISTS idx_uh_usage_event
         ON usageHistory(usageEventId) WHERE usageEventId IS NOT NULL\`
    );
  },
};

export default migration;
`;
}

function renderPgCutoverLog() {
  return `// AUTO-GENERATED by scripts/migrate-sqlite-ddl-to-pg.mjs — do not edit.
// Migration #18 — cutover log table for the PG engine. New table that
// records every cutover / rollback / test event.

const migration = {
  version: 18,
  name: "pg-cutover-log",
  up(adapter) {
    adapter.exec(
      \`CREATE TABLE IF NOT EXISTS pgCutoverLog (
        id BIGSERIAL PRIMARY KEY,
        at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
        type TEXT NOT NULL CHECK (type IN ('cutover', 'rollback', 'test')),
        ok BOOLEAN NOT NULL,
        durationMs INTEGER,
        schemaVersion INTEGER,
        tablesMigrated INTEGER,
        rowsMigrated INTEGER,
        errorCode TEXT,
        errorMessage TEXT
      )\`
    );
    adapter.exec(\`CREATE INDEX IF NOT EXISTS idx_pgcl_at ON pgCutoverLog(at DESC)\`);
  },
};

export default migration;
`;
}

function renderIndex() {
  return `// AUTO-GENERATED by scripts/migrate-sqlite-ddl-to-pg.mjs — do not edit.
// Registry for the parallel PG migration set. Imports every versioned
// migration in version order and exposes PG_MIGRATIONS + pgLatestVersion.

import m001 from "./001-initial.js";
import m002 from "./002-mcp-gateway.js";
import m003 from "./003-mcp-grant-tools.js";
import m004 from "./004-daily-token-limit.js";
import m005 from "./005-api-key-expiry.js";
import m006 from "./006-api-key-policy.js";
import m007 from "./007-provider-quota-snapshots.js";
import m008 from "./008-quota-reservations.js";
import m009 from "./009-encrypt-credentials.js";
import m010 from "./010-token-saver-events.js";
import m011 from "./011-model-capability-overrides.js";
import m012 from "./012-mcp-provider-connection.js";
import m013 from "./013-combo-invariant.js";
import m014 from "./014-api-key-provider-connections.js";
import m015 from "./015-combo-members.js";
import m016 from "./016-combo-capabilities.js";
import m017 from "./017-connection-groups.js";
import m018 from "./018-pg-cutover-log.js";

export const PG_MIGRATIONS = [
  m001, m002, m003, m004, m005, m006, m007, m008, m009,
  m010, m011, m012, m013, m014, m015, m016, m017, m018,
].sort((a, b) => a.version - b.version);

export function pgLatestVersion() {
  return PG_MIGRATIONS.length ? PG_MIGRATIONS[PG_MIGRATIONS.length - 1].version : 0;
}

export { bootstrapPgMetaTable } from "./000-bootstrap.js";
`;
}

function generateAll() {
  const files = listSqliteMigrations();
  if (!files.length) {
    throw new Error(`No SQLite migrations found in ${SQLITE_MIG_DIR}`);
  }
  const out = new Map();
  out.set("000-bootstrap.js", renderBootstrap());
  for (const f of files) {
    const m = f.match(/^(\d{3})-(.+)\.js$/);
    if (!m) continue;
    const num = parseInt(m[1], 10);
    const name = m[2];
    if (num === 1) {
      out.set("001-initial.js", renderInitial());
    } else if (num === 17) {
      out.set("017-connection-groups.js", renderConnectionGroups());
    } else if (NO_OP_MIGRATIONS.has(f)) {
      out.set(`${m[1]}-${name}.js`, renderNoOp(f, num, name));
    } else if (num === 9) {
      // 009-encrypt-credentials has its own body (columnCrypto is a
      // no-op on PG; we just stamp the version).
      out.set("009-encrypt-credentials.js", `// AUTO-GENERATED by scripts/migrate-sqlite-ddl-to-pg.mjs — do not edit.
// On a fresh PG install via cutover, mirrored rows are already encrypted.
// On a fresh install with no SQLite data, there are no rows to encrypt.
// The repos call columnCrypto.encryptField at write time, so future rows
// are encrypted as they are inserted. This migration is a true no-op.

const migration = {
  version: 9,
  name: "encrypt-credentials",
  up(adapter) {
    // No-op on PG.
  },
};

export default migration;
`);
    }
  }
  out.set("018-pg-cutover-log.js", renderPgCutoverLog());
  out.set("index.js", renderIndex());
  return out;
}

const check = process.argv.includes("--check");
const generated = generateAll();
let dirty = false;

if (check) {
  for (const [name, body] of generated) {
    const target = path.join(PG_MIG_DIR, name);
    if (!existsSync(target) || readFileSync(target, "utf8") !== body) {
      console.error(`[check-postgres-migrations] mismatch: ${name}`);
      console.error(`  expected: ${body.length} bytes`);
      if (existsSync(target)) {
        const actual = readFileSync(target, "utf8");
        console.error(`  actual:   ${actual.length} bytes`);
      }
      dirty = true;
    }
  }
  if (dirty) {
    console.error("");
    console.error("Run \`node scripts/migrate-sqlite-ddl-to-pg.mjs\` to regenerate.");
    process.exit(1);
  }
  console.log(`[check-postgres-migrations] OK (${generated.size} files in sync)`);
  process.exit(0);
}

for (const [name, body] of generated) {
  const target = path.join(PG_MIG_DIR, name);
  if (existsSync(target) && readFileSync(target, "utf8") === body) continue;
  writeFileSync(target, body, "utf8");
  console.log(`[migrate-sqlite-ddl-to-pg] wrote ${name}`);
}
console.log(`[migrate-sqlite-ddl-to-pg] done (${generated.size} files)`);
